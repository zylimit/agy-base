#!/usr/bin/env node
// gen-agents.mjs — 从 .claude/agents/*.md 生成 .agents/agents/<同名>.md（Antigravity 自定义子代理）并写联合指纹。
// 用法：node .agents/scripts/gen-agents.mjs [--root <dir>] [--quiet]
//   项目根优先级：--root <dir> -> $CLAUDE_PROJECT_DIR -> 脚本位置上溯两级。
//   没有 .claude/agents/ 时退 1。覆盖写、幂等：同样的输入两次产出逐字节相同，同步落盘 .agents/.runtime/agents-gen.sha256。
//
// 由来（本机 agy CLI 实测）：
//   1. Antigravity 从 .agents/agents/<name>.md 发现自定义子代理，不读 .claude/agents/。
//   2. 缺省 tools: 为空时子代理只有只读工具（read_file/send_message/search_web 等），拿不到 write_file/run_command；
//      且 tools: 必须写 Antigravity 规范内部名（view_file / write_to_file / replace_file_content / run_command），
//      写错工具名会导致子代理启动报 tool not found 或挂起。
//   3. disallowedTools 含 Bash 的角色（progress-recorder / feedback-observer / domain-recorder）直接从 tools:
//      拿掉 run_command，由运行时硬禁；所有生成子代理都不给 invoke_subagent，硬禁二次嵌套。
//   4. cc-base 的 model: sonnet / opus 在 Antigravity 里不合法，默认一律 model: inherit 跟主 Agent 走；
//      要钉某个角色的模型写 .agents/agents-models.json（形如 {"code-reviewer":"pro"}，支持 inherit/flash/pro）。
//   5. skills: 与 memory: 写进正文开头（Antigravity 不会按 cc-base 形态预载 .claude/skills/<name>/SKILL.md）。
//   6. 失源清理：生成前只删「带本脚本生成注释、且注释里的源名等于本文件名、但 .claude/agents/ 里已无同名源」的
//      生成物；没带注释的手写文件、复制生成物改名定制的文件（注释里源名不是自己）不动。

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
export const GEN_AGENTS_SCHEMA = 'agy-gen-agents-v3.0.0';
export const GENERATED_MARKER = '由 .agents/scripts/gen-agents.mjs';
const MARK_RE_SRC = GENERATED_MARKER.replace(/\./g, '\\.');

function normalizeLf(text) {
  return String(text ?? '').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
}

function safeLstat(p) {
  try {
    return fs.lstatSync(p);
  } catch {
    return null;
  }
}

/**
 * Safely detach ONLY a symbolic link or Windows NTFS Junction without EVER recursing into or modifying its target.
 * Non-symlink paths are left untouched (returns `false`).
 * @param {string} targetPath
 * @returns {boolean}
 */
export function detachSymlinkSafe(targetPath) {
  const lst = safeLstat(targetPath);
  if (!lst || !lst.isSymbolicLink()) return false;
  if (process.platform === 'win32') {
    // On Windows, file/dangling symlinks make rmdirSync throw ENOENT/ENOTDIR — always fall through to unlinkSync.
    try {
      fs.rmdirSync(targetPath);
      return true;
    } catch {
      try {
        fs.unlinkSync(targetPath);
        return true;
      } catch (e2) {
        if (e2 && e2.code === 'ENOENT') return false;
        throw e2;
      }
    }
  }
  try {
    fs.unlinkSync(targetPath);
    return true;
  } catch (e) {
    if (e && e.code === 'ENOENT') return false;
    throw e;
  }
}

/**
 * Check if a `.agents/agents/<fileName>` file was generated by `gen-agents.mjs` for its own `<fileName>` stem.
 * @param {string} fileName
 * @param {string} content
 * @returns {boolean}
 */
export function isOwnGeneratedAgentFile(fileName, content) {
  if (!fileName.endsWith('.md')) return false;
  const m = new RegExp(`${MARK_RE_SRC} 从 \\.claude/agents/(.+?)\\.md 生成`).exec(String(content ?? ''));
  return Boolean(m && m[1] === fileName.replace(/\.md$/, ''));
}

/**
 * Compute deterministic SHA-256 fingerprint over `.claude/agents/*.md` and optional `.agents/agents-models.json`.
 * Returns `null` when `.claude/agents` directory is absent or has zero `.md` files.
 * @param {string} root
 * @returns {{ sha256: string, sourceFiles: string[] } | null}
 */
export function computeAgentsFingerprint(root) {
  const absRoot = path.resolve(root);
  const srcDir = path.join(absRoot, '.claude', 'agents');
  try {
    if (!fs.existsSync(srcDir) || !fs.statSync(srcDir).isDirectory()) return null;
  } catch {
    return null;
  }

  let files;
  try {
    files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.md') && !f.startsWith('.')).sort();
  } catch {
    return null;
  }
  if (files.length === 0) return null;

  const h = createHash('sha256');
  h.update(`${GEN_AGENTS_SCHEMA}\0`);
  for (const f of files) {
    const fp = path.join(srcDir, f);
    try {
      if (!fs.statSync(fp).isFile()) continue;
      const text = normalizeLf(fs.readFileSync(fp, 'utf8'));
      h.update(`agent:${f}\0${text}\0`);
    } catch {
      return null;
    }
  }

  const modelsFile = path.join(absRoot, '.agents', 'agents-models.json');
  try {
    if (fs.existsSync(modelsFile) && fs.statSync(modelsFile).isFile()) {
      const mText = normalizeLf(fs.readFileSync(modelsFile, 'utf8'));
      h.update(`models\0${mText}\0`);
    }
  } catch {
    // ignore unreadable models file here; generateAgents reports invalid JSON
  }

  return { sha256: h.digest('hex'), sourceFiles: files };
}

/**
 * Fast check (< 2ms) whether `.agents/agents/*.md` and `.agents/.runtime/agents-gen.sha256` match live `.claude/agents/*.md`.
 * @param {string} root
 * @returns {{ applicable: boolean, current: boolean, expectedSha: string | null }}
 */
export function areGeneratedAgentsCurrent(root) {
  const absRoot = path.resolve(root);
  const fpInfo = computeAgentsFingerprint(absRoot);
  if (!fpInfo) {
    return { applicable: false, current: true, expectedSha: null };
  }

  if (safeLstat(path.join(absRoot, '.agents'))?.isSymbolicLink()) {
    return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
  }

  const runtimeDir = path.join(absRoot, '.agents', '.runtime');
  const shaFile = path.join(runtimeDir, 'agents-gen.sha256');
  if (safeLstat(runtimeDir)?.isSymbolicLink() || safeLstat(shaFile)?.isSymbolicLink()) {
    return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
  }
  let recordedSha = '';
  try {
    recordedSha = fs.readFileSync(shaFile, 'utf8').trim();
  } catch {
    return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
  }
  if (recordedSha !== fpInfo.sha256) {
    return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
  }

  const dstDir = path.join(absRoot, '.agents', 'agents');
  try {
    const dstLst = safeLstat(dstDir);
    if (!dstLst || dstLst.isSymbolicLink() || !dstLst.isDirectory()) {
      return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
    }
    for (const f of fpInfo.sourceFiles) {
      const outPath = path.join(dstDir, f);
      const outLst = safeLstat(outPath);
      if (!outLst || outLst.isSymbolicLink() || !outLst.isFile()) {
        return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
      }
    }
    for (const g of fs.readdirSync(dstDir)) {
      if (g.endsWith('.md') && safeLstat(path.join(dstDir, g))?.isSymbolicLink()) {
        return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
      }
    }
  } catch {
    return { applicable: true, current: false, expectedSha: fpInfo.sha256 };
  }

  return { applicable: true, current: true, expectedSha: fpInfo.sha256 };
}

// 拆 frontmatter：返回 { fm: {key: value}, body }（含 cursor-base 同款首尾引号剥离）。
function parseFrontmatter(file, text, onWarn) {
  const lines = normalizeLf(text).split('\n');
  if (lines[0] !== '---') return null;
  const end = lines.indexOf('---', 1);
  if (end < 0) return null;
  const fm = {};
  for (const line of lines.slice(1, end)) {
    if (line.trim() === '' || line.trim().startsWith('#')) continue;
    const m = /^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$/.exec(line);
    if (!m) {
      if (onWarn) onWarn(`gen-agents: ${file} frontmatter 里认不出的行，已丢弃：${line}`);
      continue;
    }
    let val = m[2].trim();
    if (val.length >= 2 && val.startsWith('"') && val.endsWith('"')) {
      try {
        const parsed = JSON.parse(val);
        val = typeof parsed === 'string' ? parsed : val.slice(1, -1);
      } catch {
        val = val.slice(1, -1);
      }
    } else if (val.length >= 2 && val.startsWith("'") && val.endsWith("'")) {
      val = val.slice(1, -1).replace(/''/g, "'");
    }
    fm[m[1]] = val;
  }
  return { fm, body: lines.slice(end + 1).join('\n') };
}

/**
 * Generate `.agents/agents/*.md` from `<root>/.claude/agents/*.md` and write `.agents/.runtime/agents-gen.sha256`.
 * @param {string} root
 * @param {{ quiet?: boolean }} [opts]
 */
export function generateAgents(root, opts = {}) {
  const absRoot = path.resolve(root);
  const agentsRootDir = path.join(absRoot, '.agents');
  if (safeLstat(agentsRootDir)?.isSymbolicLink()) {
    return {
      ok: false,
      code: 1,
      error: `拒绝软链穿透：${agentsRootDir} 本身是符号链接/Junction，请先拆链后再生成子代理`,
    };
  }

  const srcDir = path.join(absRoot, '.claude', 'agents');
  const dstDir = path.join(agentsRootDir, 'agents');
  const modelsPath = path.join(agentsRootDir, 'agents-models.json');
  const quiet = Boolean(opts.quiet);

  const logOut = (msg) => {
    if (!quiet) process.stdout.write(`${msg}\n`);
  };
  const logErr = (msg) => {
    process.stderr.write(`${msg}\n`);
  };

  if (!fs.existsSync(srcDir) || !fs.statSync(srcDir).isDirectory()) {
    return {
      ok: false,
      code: 1,
      error: `没有 ${srcDir}——请先确认目标项目已安装 cc-base (.claude/agents)`,
    };
  }

  let pinned = {};
  if (fs.existsSync(modelsPath)) {
    try {
      pinned = JSON.parse(fs.readFileSync(modelsPath, 'utf8'));
    } catch (e) {
      return { ok: false, code: 1, error: `${modelsPath} 不是合法 JSON：${e.message}` };
    }
    if (!pinned || typeof pinned !== 'object' || Array.isArray(pinned)) {
      return { ok: false, code: 1, error: `${modelsPath} 顶层必须是对象，形如 {"code-reviewer":"pro"}` };
    }
  }

  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.md') && !f.startsWith('.')).sort();
  if (files.length === 0) {
    return { ok: false, code: 1, error: `${srcDir} 下没有 .md` };
  }

  detachSymlinkSafe(dstDir);
  fs.mkdirSync(dstDir, { recursive: true });
  const pruned = [];
  for (const g of fs.readdirSync(dstDir).filter((x) => x.endsWith('.md')).sort()) {
    if (files.includes(g)) continue;
    const gPath = path.join(dstDir, g);
    try {
      const gLst = safeLstat(gPath);
      if (!gLst) continue;
      if (gLst.isSymbolicLink()) {
        detachSymlinkSafe(gPath);
        pruned.push(g);
        continue;
      }
      if (!gLst.isFile()) continue;
      const content = fs.readFileSync(gPath, 'utf8');
      if (!isOwnGeneratedAgentFile(g, content)) continue;
      fs.rmSync(gPath);
      pruned.push(g);
      logOut(`gen-agents: 源头已删，清掉生成物 ${path.relative(absRoot, gPath)}`);
    } catch {
      // ignore
    }
  }

  let bad = 0;
  const generated = [];
  for (const f of files) {
    const p = parseFrontmatter(f, fs.readFileSync(path.join(srcDir, f), 'utf8'), logErr);
    if (!p || !p.fm.name || !p.fm.description) {
      logErr(`gen-agents: ${f} 认不出 frontmatter（要有 --- 包着的 name 与 description），跳过`);
      bad++;
      continue;
    }
    const { fm, body } = p;
    const name = fm.name;
    const model = typeof pinned[name] === 'string' && pinned[name] ? pinned[name] : 'inherit';

    const disallowed = fm.disallowedTools
      ? fm.disallowedTools.split(',').map((x) => x.trim()).filter(Boolean)
      : [];
    const disallowedSet = new Set(disallowed);

    // Antigravity 规范内部工具名（本机 agy CLI 实测）：
    //   view_file -> read_file；write_to_file -> write_file；replace_file_content -> edit_file；
    //   run_command -> run_command + manage_task。不给 start_subagent/invoke_subagent，硬禁嵌套。
    const tools = ['view_file', 'write_to_file', 'replace_file_content'];
    if (!disallowedSet.has('Bash')) tools.push('run_command');

    const pre = [];
    if (fm.skills) {
      const paths = fm.skills.split(',').map((s) => s.trim()).filter(Boolean)
        .map((s) => `\`.claude/skills/${s}/SKILL.md\``).join('、');
      pre.push(`开工前先完整读 ${paths}（Antigravity 不会像 Claude Code 那样把 cc-base 的 skills: 预载给子代理），再按下文行事。`);
    }
    if (disallowed.length) {
      let noSub = false;
      for (const t of disallowed) {
        if (t === 'Task' || t === 'Agent') {
          if (!noSub) pre.push('不要再派子代理。');
          noSub = true;
        } else {
          pre.push(t === 'Bash' ? '不要用 run_command（Bash）工具。' : `不要用 ${t} 工具。`);
        }
      }
    }
    if (fm.memory === 'project') {
      pre.push(`你的持久记忆在 \`.claude/agent-memory/${name}/MEMORY.md\`，先读它，改动也写回那里。`);
    }

    const desc = /:(\s|$)|\s#/.test(fm.description) || /^["'[\]{}&*!|>%@`#?-]/.test(fm.description)
      ? JSON.stringify(fm.description)
      : fm.description;

    const out = [
      '---',
      `name: ${name}`,
      `description: ${desc}`,
      'subagent: true',
      'mainAgent: false',
      `model: ${model}`,
      'tools:',
      ...tools.map((t) => `  - ${t}`),
      '---',
      '',
      `<!-- ${GENERATED_MARKER} 从 .claude/agents/${f} 生成，别手改；要钉模型写 .agents/agents-models.json -->`,
      '',
      ...(pre.length ? [pre.join('\n'), ''] : []),
      body.replace(/^\n+/, ''),
    ].join('\n');

    const dstFile = path.join(dstDir, f);
    detachSymlinkSafe(dstFile);
    fs.writeFileSync(dstFile, out.endsWith('\n') ? out : `${out}\n`, 'utf8');
    generated.push(f);
  }

  const fpInfo = computeAgentsFingerprint(absRoot);
  if (fpInfo && bad === 0) {
    const runtimeDir = path.join(agentsRootDir, '.runtime');
    const shaFile = path.join(runtimeDir, 'agents-gen.sha256');
    try {
      detachSymlinkSafe(runtimeDir);
      fs.mkdirSync(runtimeDir, { recursive: true });
      detachSymlinkSafe(shaFile);
      fs.writeFileSync(shaFile, `${fpInfo.sha256}\n`, 'utf8');
    } catch {
      // non-fatal if runtime dir read-only
    }
  }

  if (bad > 0) {
    return {
      ok: false,
      code: 1,
      generated,
      pruned,
      sha256: fpInfo?.sha256 || null,
      error: `${bad} 个 agent 文件认不出，其余已生成`,
    };
  }

  logOut(`gen-agents: 生成 ${generated.length} 个到 ${path.relative(absRoot, dstDir) || '.agents/agents'}/`);
  return {
    ok: true,
    code: 0,
    generated,
    pruned,
    sha256: fpInfo?.sha256 || null,
  };
}

function parseGenArgs(argv) {
  let rootOverride = '';
  let quiet = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--root') {
      const next = argv[++i];
      if (!next || next.startsWith('-')) {
        process.stderr.write('gen-agents: --root 需要目录参数\n');
        process.exit(2);
      }
      rootOverride = next;
    } else if (a.startsWith('--root=')) {
      rootOverride = a.slice(7);
      if (!rootOverride) {
        process.stderr.write('gen-agents: --root= 需要非空目录参数\n');
        process.exit(2);
      }
    } else if (a === '--quiet') {
      quiet = true;
    } else if (a === '-h' || a === '--help') {
      process.stdout.write('用法: node .agents/scripts/gen-agents.mjs [--root <dir>] [--quiet]\n');
      process.exit(0);
    } else {
      process.stderr.write(`gen-agents: 未知参数：${a}\n`);
      process.exit(2);
    }
  }
  const root = rootOverride
    ? path.resolve(rootOverride)
    : (process.env.CLAUDE_PROJECT_DIR || path.resolve(SCRIPT_DIR, '..', '..'));
  return { root, quiet };
}

const isMain = process.argv[1] && path.resolve(fileURLToPath(import.meta.url)) === path.resolve(process.argv[1]);
if (isMain) {
  const { root, quiet } = parseGenArgs(process.argv.slice(2));
  const res = generateAgents(root, { quiet });
  if (!res.ok) {
    process.stderr.write(`gen-agents: ${res.error}\n`);
    process.exit(res.code || 1);
  }
}
